#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""
生成考题一用的脏样例数据 sales_raw.xlsx（19 行，含 6 行脏数据）。

脏数据类型：
  - 关键字段缺失：日期空 1 行、销售员空 1 行、单价空 1 行
  - 数量异常：0 与 -3 各 1 行
  - 全字段重复：第 1 行重复出现 1 次
有效数据 13 行，销售额总额 28520.00 元（可人工核对）。

运行：python data/make_dirty_sample.py
"""

from pathlib import Path

import pandas as pd

BASE_DIR = Path(__file__).resolve().parent

ROWS = [
    # 日期, 销售员, 产品, 数量, 单价, 地区
    ("2026-09-01", "张三", "笔记本", 2, 5000, "华东"),
    ("2026-09-03", "张三", "鼠标", 10, 80, "华南"),
    ("2026-09-05", "李四", "显示器", 3, 1200, "华南"),
    ("2026-09-08", "李四", "键盘", 5, 200, "华南"),
    ("2026-09-10", "王五", "打印机", 1, 2500, "华北"),
    ("2026-09-12", "王五", "墨盒", 8, 150, "华北"),
    ("2026-09-15", "赵六", "笔记本", 1, 5000, "西南"),
    ("2026-09-18", "赵六", "鼠标", 4, 80, "西南"),
    ("2026-09-20", "张三", "显示器", 2, 1200, "华东"),
    ("2026-09-22", "李四", "打印机", 2, 2500, "华南"),
    ("2026-09-25", "王五", "键盘", 6, 200, "华北"),
    ("2026-09-28", "赵六", "墨盒", 3, 150, "西南"),
    ("2026-09-26", "赵六", "键盘", 2, 200, "西南"),
    # --- 脏数据开始 ---
    ("2026-09-29", "张三", "鼠标", 0, 80, "华东"),      # 数量 0
    ("2026-09-30", "李四", "键盘", -3, 200, "华南"),     # 数量负数
    (None, "王五", "笔记本", 2, 5000, "华北"),           # 日期缺失
    ("2026-10-02", None, "显示器", 1, 1200, "华东"),      # 销售员缺失
    ("2026-09-01", "张三", "笔记本", 2, 5000, "华东"),    # 与第 1 行完全重复
    ("2026-10-05", "王五", "鼠标", 3, None, "华北"),      # 单价缺失
]


def main() -> None:
    df = pd.DataFrame(ROWS, columns=["日期", "销售员", "产品", "数量", "单价", "地区"])
    target = BASE_DIR / "sales_raw.xlsx"
    df.to_excel(target, index=False, sheet_name="sales_raw")
    print(f"已生成 {target}，共 {len(df)} 行（其中脏数据 6 行）")


if __name__ == "__main__":
    main()
